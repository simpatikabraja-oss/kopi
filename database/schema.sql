-- Jalankan di Supabase SQL Editor. Tabel ini hanya diakses lewat server API
-- memakai service-role key; jangan pernah membagikan service-role key ke browser.

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_id text not null unique,
  payment_status text not null check (payment_status in ('PENDING', 'PAID', 'FAILED')),
  payment_method text not null check (payment_method in ('MIDTRANS', 'CASH')),
  amount integer not null check (amount > 0),
  customer_name text not null,
  customer_class text not null,
  customer_phone text not null,
  customer_email text,
  pickup_method text not null,
  customer_note text,
  line_items jsonb not null,
  midtrans_token text,
  midtrans_redirect_url text,
  midtrans_transaction_status text,
  midtrans_fraud_status text,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.orders enable row level security;
-- Tidak ada policy publik. Service role pada API tetap dapat menulis/memperbarui.
